/** KPI tile: label, one primary number, one line of context, optional drill-down. */
export function Kpi({ label, value, sub, tone = 'default', onClick, loading, badge }) {
  const toneCls = { default: 'text-white', critical: 'text-risk-critical', warn: 'text-risk-high', good: 'text-risk-low', gold: 'text-gold' }[tone];
  const Tag = onClick ? 'button' : 'div';
  return (
    <Tag
      onClick={onClick}
      className={`card text-left p-4 min-w-0 ${onClick ? 'card-hover cursor-pointer focus-visible:outline-none' : ''}`}
    >
      <div className="flex items-center justify-between gap-2">
        <span className="text-[11px] uppercase tracking-wide text-gray-500 font-semibold leading-tight">{label}</span>
        {badge}
      </div>
      {loading ? <Skeleton className="h-8 w-24 mt-2" /> : <div className={`text-[26px] leading-tight font-bold tabular-nums tracking-tight mt-1 truncate ${toneCls}`}>{value}</div>}
      {sub && <div className="text-xs text-gray-500 mt-1 leading-snug">{sub}</div>}
    </Tag>
  );
}

/* ---------- severity scale: one place so every page agrees ---------- */
export const SEVERITY = {
  critical: { label: 'Critical', color: '#f43f5e', text: 'text-risk-critical', bg: 'bg-risk-critical' },
  high: { label: 'High', color: '#f59e0b', text: 'text-risk-high', bg: 'bg-risk-high' },
  medium: { label: 'Medium', color: '#38bdf8', text: 'text-risk-medium', bg: 'bg-risk-medium' },
  low: { label: 'Low', color: '#34d399', text: 'text-risk-low', bg: 'bg-risk-low' },
};
export const SEVERITY_ORDER = ['critical', 'high', 'medium', 'low'];

/** Accessible tablist (arrow keys, roving tabindex). Panels are rendered by the caller. */
export function Tabs({ tabs, value, onChange, label = 'Sections', className = '' }) {
  const onKey = (e) => {
    const i = tabs.findIndex((t) => t.id === value);
    if (e.key === 'ArrowRight') onChange(tabs[(i + 1) % tabs.length].id);
    if (e.key === 'ArrowLeft') onChange(tabs[(i - 1 + tabs.length) % tabs.length].id);
  };
  return (
    <div role="tablist" aria-label={label} onKeyDown={onKey} className={`flex gap-1 border-b border-white/[0.08] overflow-x-auto ${className}`}>
      {tabs.map((t) => (
        <button key={t.id} role="tab" id={`tab-${t.id}`} aria-selected={value === t.id} aria-controls={`panel-${t.id}`}
          tabIndex={value === t.id ? 0 : -1} onClick={() => onChange(t.id)} className="tab whitespace-nowrap">
          {t.label}{t.count != null && <span className="ml-1.5 text-[11px] text-gray-500 tabular-nums">{t.count}</span>}
        </button>
      ))}
    </div>
  );
}

/** Horizontal 0-100 scale with the severity bands drawn behind the marker. */
export function RiskMeter({ score, level }) {
  const s = Math.max(0, Math.min(100, score ?? 0));
  return (
    <div role="img" aria-label={`Risk score ${s.toFixed(0)} out of 100, ${level}`}>
      <div className="relative h-2.5 rounded-full overflow-hidden flex">
        <span className="h-full bg-risk-low/35" style={{ width: '40%' }} />
        <span className="h-full bg-risk-medium/35" style={{ width: '20%' }} />
        <span className="h-full bg-risk-high/35" style={{ width: '20%' }} />
        <span className="h-full bg-risk-critical/35" style={{ width: '20%' }} />
      </div>
      <div className="relative h-3">
        <span className="absolute -top-1.5 w-0 h-0 border-x-[5px] border-x-transparent border-b-[7px] border-b-white transition-all duration-500" style={{ left: `calc(${s}% - 5px)` }} />
      </div>
      <div className="flex justify-between text-[10px] text-gray-600 tabular-nums"><span>0</span><span>40</span><span>60</span><span>80</span><span>100</span></div>
    </div>
  );
}

/** Stacked proportional bar for a {critical, high, medium, low} count map, with a legend carrying the numbers. */
export function DistributionBar({ levels, onPick, active }) {
  const total = SEVERITY_ORDER.reduce((s, k) => s + (levels?.[k] || 0), 0) || 1;
  return (
    <div>
      <div className="flex h-3 rounded-full overflow-hidden bg-white/[0.04]" role="img"
        aria-label={SEVERITY_ORDER.map((k) => `${levels?.[k] || 0} ${k}`).join(', ')}>
        {SEVERITY_ORDER.map((k) => <span key={k} title={`${SEVERITY[k].label}: ${fmt.int(levels?.[k] || 0)}`} className="h-full transition-all duration-500" style={{ width: `${((levels?.[k] || 0) / total) * 100}%`, background: SEVERITY[k].color }} />)}
      </div>
      <ul className="grid grid-cols-2 sm:grid-cols-4 gap-2 mt-3">
        {SEVERITY_ORDER.map((k) => (
          <li key={k}>
            <button type="button" onClick={() => onPick?.(active === k ? '' : k)} aria-pressed={active === k} disabled={!onPick}
              className={`w-full text-left rounded-lg px-2.5 py-1.5 border transition-colors ${active === k ? 'border-gold/40 bg-gold/10' : 'border-transparent hover:bg-white/[0.04]'} disabled:hover:bg-transparent disabled:opacity-100`}>
              <span className="flex items-center gap-1.5 text-[11px] text-gray-400"><span className="w-2 h-2 rounded-full" style={{ background: SEVERITY[k].color }} />{SEVERITY[k].label}</span>
              <span className="block text-lg font-bold tabular-nums text-white leading-tight">{fmt.int(levels?.[k] || 0)}</span>
              <span className="block text-[10px] text-gray-500 tabular-nums">{fmt.pct((levels?.[k] || 0) / total, 1)}</span>
            </button>
          </li>
        ))}
      </ul>
    </div>
  );
}

/** Ranked horizontal bars with labels, values and a unit; bars grow in once. */
export function BarList({ items, unit = '%', max, tone = '#d4af37', labelWidth = 128 }) {
  const top = max ?? Math.max(...items.map((i) => i.value), 1);
  return (
    <ul className="space-y-1.5">
      {items.map((it, idx) => (
        <li key={it.label} className="grid items-center gap-3 text-xs" style={{ gridTemplateColumns: `${labelWidth}px 1fr 44px` }} title={it.hint}>
          <span className="text-gray-300 truncate">{it.label}</span>
          <span className="h-2 rounded-full bg-white/[0.05] overflow-hidden">
            <span className="block h-full rounded-full grow-x" style={{ '--i': idx, width: `${(it.value / top) * 100}%`, background: it.color || tone }} />
          </span>
          <span className="text-right tabular-nums text-gray-200">{it.value}{unit}</span>
        </li>
      ))}
    </ul>
  );
}

export function Chip({ active, children, ...rest }) {
  return (
    <button
      {...rest}
      aria-pressed={active}
      className={`btn-chip border ${active ? 'bg-gold/15 border-gold/40 text-gold' : 'bg-white/[0.03] border-white/10 text-gray-400 hover:text-gray-200'}`}
    >
      {children}
    </button>
  );
}
